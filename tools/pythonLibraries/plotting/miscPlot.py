from __future__ import division

import colorsys

import numpy as np

from matplotlib import rc
import matplotlib.pyplot as plt


def get_color(color):
    for hue in range(color):
        hue = 1. * hue / color
        col = [int(x) for x in colorsys.hsv_to_rgb(hue, 1.0, 230)]
        yield "#{0:02x}{1:02x}{2:02x}".format(*col)

